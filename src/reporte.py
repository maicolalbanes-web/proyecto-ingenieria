from datetime import datetime
from collections import Counter

def generar_estadisticas(registros: list) -> str:
    """
    Calcula las estadisticas de las PQRS, las muestra en pantalla
    y devuelve todo el texto del reporte para poder descargarlo o imprimirlo.
    """
    if not registros:
        print("\nNo hay registros disponibles para calcular estadisticas.")
        return ""

    # Lista donde vamos guardando cada linea del reporte
    lineas = []
    lineas.append("=" * 60)
    lineas.append("REPORTE DE ESTADISTICAS DE GESTION PQRS")
    lineas.append("Fecha del reporte: " + datetime.now().strftime("%Y-%m-%d %H:%M"))
    lineas.append("=" * 60)

    # 1. Promedio entero de dias en dar respuesta
    dias_respuesta = []
    for r in registros:
        if r["estado_peticion"] == "Solucionada" and r.get("fecha_solucion") not in (None, "N/A"):
            f_rad = datetime.strptime(r["fecha_radicacion"], "%Y-%m-%d")
            f_sol = datetime.strptime(r["fecha_solucion"], "%Y-%m-%d")
            dias = max(0, (f_sol - f_rad).days)
            dias_respuesta.append(dias)

    if dias_respuesta:
        promedio_dias = round(sum(dias_respuesta) / len(dias_respuesta))
        lineas.append(f"1. [OBLIGATORIA] Promedio de dias para dar respuesta: {promedio_dias} dia(s)")
    else:
        lineas.append("1. [OBLIGATORIA] Promedio de dias para dar respuesta: Sin PQRS solucionadas aun.")

    # 2. Cantidad registrada por cada tipo de solicitud
    conteo_tipos = Counter(r["tipo_solicitud"] for r in registros)
    lineas.append("\n2. Cantidad de registros por tipo de solicitud:")
    for tipo in ["Peticion", "Queja", "Reclamo", "Sugerencia"]:
        lineas.append(f"   - {tipo}: {conteo_tipos.get(tipo, 0)}")

    # 3. Cantidad de registros por tipo de mascota
    conteo_mascotas = Counter(r["tipo_mascota"] for r in registros)
    lineas.append("\n3. Distribucion por tipo de mascota:")
    lineas.append(f"   - Perro: {conteo_mascotas.get('Perro', 0)}")
    lineas.append(f"   - Gato:  {conteo_mascotas.get('Gato', 0)}")

    # 4. Registros activos proximos a vencer (<= 5 dias restantes)
    hoy = datetime.now().date()
    proximos_vencer = []
    for r in registros:
        if r["estado_peticion"] != "Solucionada":
            f_max = datetime.strptime(r["fecha_maxima_respuesta"], "%Y-%m-%d").date()
            dias_restantes = (f_max - hoy).days
            if dias_restantes <= 5:
                proximos_vencer.append((r, dias_restantes))

    lineas.append(f"\n4. PQRS activas proximas a vencer o vencidas (<= 5 dias): {len(proximos_vencer)}")
    for r, d in proximos_vencer:
        lineas.append(f"   - [{r['tipo_solicitud']} ID {r['id']}] {r['asunto_titulo'][:35]} (Faltan {d} dias)")

    # 5. Registro activo mas antiguo
    activos = [r for r in registros if r["estado_peticion"] != "Solucionada"]
    lineas.append("\n5. PQRS activa mas antigua:")
    if activos:
        mas_antiguo = min(activos, key=lambda x: datetime.strptime(x["fecha_radicacion"], "%Y-%m-%d"))
        lineas.append(f"   - [{mas_antiguo['tipo_solicitud']} ID {mas_antiguo['id']}] Fecha: {mas_antiguo['fecha_radicacion']} | Asunto: {mas_antiguo['asunto_titulo']}")
    else:
        lineas.append("   - No hay PQRS activas actualmente.")

    # 6. Distribucion de PQRS por Campus Universitario
    conteo_campus = Counter(r["campus_relacionado"] for r in registros)
    lineas.append("\n6. Top Campus con mayor numero de solicitudes:")
    for campus, cant in conteo_campus.most_common():
        lineas.append(f"   - {campus}: {cant}")

    lineas.append("=" * 60)

    # Unimos todas las lineas en un solo texto, lo mostramos y lo retornamos
    reporte_completo = "\n".join(lineas)
    print("\n" + reporte_completo + "\n")
    return reporte_completo