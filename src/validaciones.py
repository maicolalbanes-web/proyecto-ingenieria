def validar_nombre(nombre: str) -> bool:
    """Revisa que el nombre tenga entre 3 y 100 letras."""
    nombre = nombre.strip()
    if not (3 <= len(nombre) <= 100):
        return False
    patron = r"^[A-Za-zÁÉÍÓÚáéíóúÑñ\s'-]+$"
    return bool(re.match(patron, nombre))

def validar_numero_documento(doc: str) -> bool:
    """Comprueba que solo tenga numeros y entre 3 y 15 digitos."""
    return doc.isdigit() and (3 <= len(doc) <= 15)

def validar_telefono(tel: str) -> bool:
    """Verifica que el telefono sea numerico y tenga 10 digitos."""
    return tel.isdigit() and len(tel) == 10

def validar_correo(correo: str) -> bool:
    """Verifica que el correo tenga un '@' y un punto '.'."""
    if len(correo) > 254 or correo.count("@") != 1:
        return False
    patron = r"^[\w\.-]+@[\w\.-]+\.\w+$"
    return bool(re.match(patron, correo))

def validar_direccion(direccion: str) -> bool:
    """Valida que la direccion este vacia (opcional) o tenga entre 5 y 200 caracteres."""
    if direccion.strip() == "":
        return True
    if not (5 <= len(direccion.strip()) <= 200):
        return False
    patron = r"^[A-Za-z0-9ÁÉÍÓÚáéíóúÑñ\s#\-\./]+$"
    return bool(re.match(patron, direccion.strip()))

def validar_fecha(fecha_str: str):
    """Valida el formato AAAA-MM-DD y que la fecha no sea futura."""
    try:
        fecha = datetime.strptime(fecha_str, "%Y-%m-%d")
        if fecha.date() > datetime.now().date():
            return None
        return fecha
    except ValueError:
        return None

