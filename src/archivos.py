# --- NUEVAS FUNCIONES PARA GUARDAR Y VERIFICAR USUARIOS ---

def guardar_usuario(usuario: str, contraseña: str) -> bool:
    """
    Guarda un nuevo usuario y contraseña en 'usuarios.txt'.
    Retorna False si el usuario ya existe, o True si se creo correctamente.
    """
    ruta = os.path.join(RUTA_DATA, ARCHIVO_USUARIOS)

    # Revisar linea por linea si el nombre de usuario ya fue creado
    with open(ruta, "r", encoding="utf-8") as f:
        for linea in f:
            if linea.strip() != "":
                datos = linea.strip().split("|")
                if datos[0] == usuario:
                    return False  # El usuario ya existe

    # Guardar el nuevo usuario separado por '|'
    with open(ruta, "a", encoding="utf-8") as f:
        f.write(f"{usuario}|{contraseña}\n")
    return True

def verificar_usuario(usuario: str, contraseña: str) -> bool:
    """
    Busca en 'usuarios.txt' si el usuario y la contraseña coinciden.
    Retorna True si son correctos, o False si no coinciden.
    """
    ruta = os.path.join(RUTA_DATA, ARCHIVO_USUARIOS)
    with open(ruta, "r", encoding="utf-8") as f:
        for linea in f:
            if linea.strip() != "":
                datos = linea.strip().split("|")
                if datos[0] == usuario and datos[1] == contraseña:
                    return True
    return False

