    ANCHO = 120
    borde = "+" + "-" * (ANCHO - 2) + "+"

    def linea_centrada(texto: str) -> str:
        return "|" + texto[:ANCHO - 4].center(ANCHO - 2) + "|"

    def linea_izquierda(texto: str) -> str:
        return "| " + texto[:ANCHO - 4].ljust(ANCHO - 3) + "|"

    lineas = [
        borde,
        linea_centrada("PAWFAVOR - GESTOR  PQRS (PROJECT NEXUS)"),
        linea_centrada("COMPROBANTE OFICIAL DE RADICACION"),
        borde,
        linea_izquierda(f"ID Radicado: {int(reg['id']):05d} | Tipo: {reg['tipo_solicitud']} | Estado: {reg['estado_peticion']}"),
        linea_izquierda(f"Fecha Radicación: {reg['fecha_radicacion']} | Fecha Maxima Respuesta: {reg['fecha_maxima_respuesta']}"),
        borde,
        linea_centrada("DATOS DEL SOLICITANTE"),
        borde,
        linea_izquierda(f"Nombre Completo: {reg['nombre_completo']}"),
        linea_izquierda(f"Documento: {reg['tipo_documento']} - {reg['numero_documento']}"),
        linea_izquierda(f"Telefono ({reg['tipo_telefono']}): {reg['telefono_contacto']} | Correo: {reg['correo_electronico']}"),
        linea_izquierda(f"Direccion: {reg['direccion']}"),
        borde,
        linea_centrada("CLASIFICACION Y RESUMEN DE LA SOLICITUD"),
        borde,
        linea_izquierda(f"Canal de Recepcion: {reg['canal_recepcion']} | Mascota: {reg['tipo_mascota']}"),
        linea_izquierda(f"Campus Relacionado: {reg['campus_relacionado']}"),
        linea_izquierda(f"Asunto: {reg['asunto_titulo']}"),
        borde
    ]
    comprobante = "\n".join(lineas)

    nombre_txt = f"Radicado_{reg['tipo_solicitud']}_{int(reg['id']):05d}.txt"
    ruta_txt = os.path.join(RUTA_DATA, nombre_txt)
    with open(ruta_txt, "w", encoding="utf-8") as f:
        f.write(comprobante)

    return comprobante