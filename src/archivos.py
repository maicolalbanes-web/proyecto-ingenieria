import os
from datetime import datetime, timedelta

# Carpeta donde se guardaran todos los archivos de texto
try:
    RUTA_DATA = os.path.join(os.path.dirname(__file__), "..", "data")
except NameError:
    RUTA_DATA = os.path.join(os.getcwd(), "data")

# Archivos de texto para cada tipo de solicitud
MAPA_ARCHIVOS = {
    "Peticion": "Peticion.txt",
    "Queja": "Queja.txt",
    "Reclamo": "Reclamo.txt",
    "Sugerencia": "Sugerencia.txt"
}

# Archivo donde se guardan los usuarios y contrasenas del administrador
ARCHIVO_USUARIOS = "usuarios.txt"

CAMPOS = [
    "id", "nombre_completo", "tipo_documento", "numero_documento",
    "tipo_telefono", "telefono_contacto", "correo_electronico", "direccion",
    "tipo_solicitud", "fecha_radicacion", "canal_recepcion", "asunto_titulo",
    "descripcion_detallada", "tipo_mascota", "campus_relacionado",
    "fecha_maxima_respuesta", "estado_peticion", "fecha_solucion"
]

