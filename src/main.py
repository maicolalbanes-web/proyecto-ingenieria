def modulo_registrar_cambios():
    """Permite cambiar el estado de una PQRS siguiendo el flujo permitido."""
    print("\n--- 3. REGISTRAR CAMBIO DE ESTADO EN PQRS ---")
    tipo = seleccionar_de_lista("Tipo de solicitud", TIPOS_SOLICITUD)
    id_buscar = input("Ingrese el ID numérico del radicado a actualizar: ").strip()
    if not id_buscar.isdigit():
        print("ID invalido.")
        return

    registros = leer_todos_registros()
    actual = None
    for r in registros:
        if r["tipo_solicitud"] == tipo and int(r["id"]) == int(id_buscar):
            actual = r
            break

    if not actual:
        print("No se encontro el registro especificado.")
        return

    print(f"Estado actual: {actual['estado_peticion']}")
    if actual["estado_peticion"] == "Solucionada":
        print("Esta PQRS ya se encuentra Solucionada y no admite mas cambios.")
        return

    nuevo_estado = seleccionar_de_lista("Nuevo estado", ESTADOS_FLUJO)
    if validar_cambio_estado(actual["estado_peticion"], nuevo_estado):
        if actualizar_estado_registro(tipo, actual["id"], nuevo_estado):
            print(f"Estado actualizado correctamente a '{nuevo_estado}'.")
        else:
            print("Ocurrio un error al guardar el cambio.")
    else:
        print("Cambio invalido. El flujo obligatorio es: Registrada -> En proceso -> Solucionada.")

