def seleccionar_de_lista(titulo: str, opciones: list) -> str:
    """Muestra una lista numerada y obliga a elegir una opcion valida."""
    print(f"\nSeleccione {titulo}:")
    for idx, op in enumerate(opciones, 1):
        print(f"  {idx}. {op}")
    while True:
        entrada = input("Ingrese el numero de opcion: ").strip()
        if entrada.isdigit() and 1 <= int(entrada) <= len(opciones):
            return opciones[int(entrada) - 1]
        print("Opcion invalida. Intente de nuevo.")

def pedir_dato(mensaje: str, funcion_validacion, error_msg: str) -> str:
    """Pide un dato por consola repetidamente hasta que pase la validacion."""
    while True:
        valor = input(mensaje).strip()
        if funcion_validacion(valor):
            return valor
        print(f"Error: {error_msg}")

